import Foundation
import JavaScriptCore

struct BuiltInSitesTests {
    static func run(resources sourceResources: URL) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let resources = directory.appendingPathComponent("resources")
        try FileManager.default.createDirectory(at: resources, withIntermediateDirectories: true)
        let bundledList = sourceResources.deletingLastPathComponent().appendingPathComponent("list")
        try FileManager.default.createSymbolicLink(at: resources.appendingPathComponent("list"), withDestinationURL: bundledList)
        try FileManager.default.createSymbolicLink(at: resources.appendingPathComponent("routing"), withDestinationURL: sourceResources.appendingPathComponent("routing"))
        let file = directory.appendingPathComponent("builtin-sites.json")
        let absent = try BuiltInSitesStore.load(file: file)
        precondition(absent == nil)
        let store = BuiltInSitesStore(resources: resources, file: file)
        precondition(store.error.isEmpty && !store.isOverridden && store.text.contains("openai.com"))
        let defaults = store.text
        let validatedDefaults = try BuiltInSitesStore.validated(defaults)
        precondition(!validatedDefaults.isEmpty, "All bundled entries must be editable and saveable")
        for invalid in ["https://example.com", "example.com/path", "127.0.0.1", "::1", "test.local", "localhost", "foo..com", "example.com # comment", "*.example.com"] {
            store.text = "valid.example\n" + invalid
            store.save()
            precondition(!store.error.isEmpty && !FileManager.default.fileExists(atPath: file.path), "Invalid line must not partially save")
        }
        store.text = " Example.COM \n\napi.example.com\nexample.com"
        store.save()
        precondition(store.error.isEmpty && store.isOverridden)
        let saved = try BuiltInSitesStore.load(file: file)
        precondition(saved == ["api.example.com", "example.com"])
        let permissions = try FileManager.default.attributesOfItem(atPath: file.path)[.posixPermissions] as? NSNumber
        precondition(permissions?.intValue == 0o600)
        let original = try DomainRules.load(from: resources.appendingPathComponent("list"))
        let edited = try DomainRules.load(from: resources.appendingPathComponent("list"), baseDomains: saved)
        let abroad = try foreignDomains(resources: resources, youtube: true, baseDomains: saved)
        precondition(edited.included == saved && abroad == saved && original.excluded == edited.excluded)
        precondition(!abroad.contains("openai.com"), "Deleted built-in site must not reappear in foreign routes")
        precondition(!ForeignProbe.shouldProbeAPI(foreignDomains: abroad, directDomains: []))
        precondition(ForeignProbe.shouldProbeAPI(foreignDomains: ["openai.com"], directDomains: []))
        precondition(!ForeignProbe.shouldProbeAPI(foreignDomains: ["openai.com"], directDomains: ["api.openai.com"]))
        precondition(!ForeignProbe.shouldProbeAPI(foreignDomains: ["notopenai.com", "openai.com.evil"], directDomains: []))
        let filtered = try foreignDomains(resources: resources, youtube: false, baseDomains: ["youtube.com", "openai.com"])
        precondition(filtered == ["openai.com"], "YouTube toggle still filters overridden foreign list")
        let videoSubdomains = try foreignDomains(resources: resources, youtube: false, baseDomains: ["www.youtube.com", "a.b.googlevideo.com", "notyoutube.com", "youtube.com.example", "openai.com"])
        precondition(videoSubdomains == ["notyoutube.com", "openai.com", "youtube.com.example"], "YouTube subdomains must be filtered without matching unrelated suffixes")
        let context = JSContext()!
        context.evaluateScript("function isPlainHostName(h) { return h.indexOf('.') < 0; }")
        context.evaluateScript(try edited.pac(port: 1088, allSites: false, foreign: abroad, useHTTPProxy: true))
        func route(_ host: String) -> String {
            context.objectForKeyedSubscript("FindProxyForURL")!.call(withArguments: ["https://\(host)/", host])!.toString()!
        }
        precondition(route("api.openai.com") == "DIRECT" && route("example.com") == "PROXY 127.0.0.1:1088")
        store.text = "\n \n"
        store.save()
        let empty = try BuiltInSitesStore.load(file: file)
        precondition(empty == [] && store.isOverridden && store.text.isEmpty)
        precondition(BuiltInSitesStore(resources: resources, file: file).isOverridden)
        let emptySelected = try DomainRules.load(from: resources.appendingPathComponent("list"), baseDomains: empty)
        let emptyForeign = try foreignDomains(resources: resources, youtube: true, baseDomains: empty)
        precondition(emptySelected.included.isEmpty && emptyForeign.isEmpty)
        context.evaluateScript(try emptySelected.pac(port: 1088, allSites: true, foreign: emptyForeign, useHTTPProxy: true))
        precondition(route("api.openai.com") == "PROXY 127.0.0.1:1088", "Empty foreign list must retain router HTTP frontend in all-sites mode")
        context.evaluateScript(try emptySelected.pac(port: 1088, allSites: false, foreign: emptyForeign, useHTTPProxy: true))
        precondition(route("api.openai.com") == "DIRECT", "Empty selected list must remain empty")
        store.restoreDefaults()
        let restored = try BuiltInSitesStore.load(file: file)
        precondition(restored == nil && !store.isOverridden && store.text == defaults)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let editorFile = directory.appendingPathComponent("editor-sites.json")
        let editor = BuiltInSitesStore(resources: resources, file: editorFile)
        precondition(editor.category(for: "api.openai.com") == .ai)
        precondition(editor.category(for: "www.youtube.com") == .video)
        precondition(editor.category(for: "www.instagram.com") == .social)
        precondition(editor.category(for: "unknown.example") == .other)
        precondition(editor.filteredSites(search: " OPENAI ", category: .ai).map { $0.domain }.contains("openai.com"))
        precondition(editor.filteredSites(search: "openai", category: .video).isEmpty)
        editor.setEnabled("openai.com", false)
        precondition(!editor.enabledDomains.contains("openai.com") && editor.hasUnsavedChanges)
        precondition(!FileManager.default.fileExists(atPath: editorFile.path), "Toggle is a draft until explicit save")
        precondition(editor.add("DISABLED.EXAMPLE"))
        editor.setEnabled("disabled.example", false)
        editor.save()
        precondition(editor.error.isEmpty && !editor.hasUnsavedChanges)
        let editorReloaded = BuiltInSitesStore(resources: resources, file: editorFile)
        precondition(editorReloaded.sites.contains(BuiltInSite(domain: "openai.com", enabled: false)))
        precondition(editorReloaded.sites.contains(BuiltInSite(domain: "disabled.example", enabled: false)), "Disabled custom row must survive restart")
        let uiFile = directory.appendingPathComponent("editor-sites-ui.json")
        let uiPermissions = try FileManager.default.attributesOfItem(atPath: uiFile.path)[.posixPermissions] as? NSNumber
        precondition(uiPermissions?.intValue == 0o600)
        editorReloaded.remove("disabled.example")
        precondition(!editorReloaded.sites.contains { $0.domain == "disabled.example" })
        editorReloaded.undoDelete()
        precondition(editorReloaded.sites.contains(BuiltInSite(domain: "disabled.example", enabled: false)), "Undo must preserve disabled state")
        editorReloaded.setEnabled("openai.com", true)
        precondition(editorReloaded.text.components(separatedBy: .newlines).contains("openai.com"))
        editorReloaded.text = "youtube.com\nnew.example"
        precondition(editorReloaded.textIsDirty)
        precondition(editorReloaded.applyText())
        precondition(editorReloaded.enabledDomains == ["new.example", "youtube.com"])
        precondition(editorReloaded.sites.contains(BuiltInSite(domain: "openai.com", enabled: false)), "Text mode must preserve omitted rows as disabled")
        editorReloaded.text = "https://invalid.example"
        editorReloaded.setEnabled("youtube.com", false)
        precondition(!editorReloaded.error.isEmpty && editorReloaded.enabledDomains.contains("youtube.com"), "Invalid text must block list mutations")
        editorReloaded.discardText()
        precondition(!editorReloaded.textIsDirty && editorReloaded.text == "new.example\nyoutube.com")
        editorReloaded.save()
        precondition(editorReloaded.error.isEmpty)
        // An externally changed route list takes precedence over stale editor metadata.
        try JSONEncoder().encode(["outside.example"]).write(to: editorFile, options: .atomic)
        precondition(editorReloaded.add("draft.example"))
        editorReloaded.save()
        precondition(!editorReloaded.error.isEmpty, "Saving must not clobber external edits")
        let outside = try BuiltInSitesStore.load(file: editorFile)
        precondition(outside == ["outside.example"])
        editorReloaded.reload()
        precondition(editorReloaded.sites == [BuiltInSite(domain: "outside.example", enabled: true)], "Stale UI state must not reintroduce externally removed routes")
        editorReloaded.remove("outside.example")
        editorReloaded.save()
        let cleared = try BuiltInSitesStore.load(file: editorFile)
        precondition(cleared == [], "Deleting last row saves an explicit empty override")
        editorReloaded.undoDelete()
        precondition(editorReloaded.hasUnsavedChanges && editorReloaded.enabledDomains == ["outside.example"])
        editorReloaded.restoreDefaults()
        precondition(!editorReloaded.isOverridden && !FileManager.default.fileExists(atPath: uiFile.path))
        try Data("[\"example.com\\nother.com\"]".utf8).write(to: file)
        do { _ = try BuiltInSitesStore.load(file: file); preconditionFailure("Malformed JSON domain entry accepted") } catch { }
        print("PASS: site editor search/categories, persistent toggles, undo, text/list synchronization, external-edit conflict, empty/default routes and probe policy")
    }
}
